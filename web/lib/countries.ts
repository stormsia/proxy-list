export function getCountryDisplayName(
  code: string,
  fallbackName?: string,
  lang: "en" | "ru" = "en"
): string {
  const normalized = code.toLowerCase();
  const meta = COUNTRY_META[normalized];
  if (meta) {
    return lang === "ru" ? meta.nameRu : meta.name;
  }
  return fallbackName || code.toUpperCase();
}
